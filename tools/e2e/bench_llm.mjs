import { chromium } from 'playwright';
const MODEL = process.argv[2] || 'qwen25-0.5b-cpu';
const ctx = await chromium.launchPersistentContext('./.profile-ai', { args: ['--no-sandbox','--use-gl=swiftshader','--enable-unsafe-swiftshader'] });
const page = ctx.pages()[0] || await ctx.newPage();
page.on('console', m => console.log('   page:', m.text().slice(0,200)));
await page.goto('http://127.0.0.1:8766/ai-lab.html', { waitUntil: 'domcontentloaded' });
const out = await page.evaluate(async (MODEL) => {
  const step = (s) => console.log('STEP ' + s);
  const { MODEL_CATALOG, createRuntime } = await import('./ai/model_manager.js');
  const { BATCH_SCHEMA } = await import('./ai/json_schema.js');
  const { buildBatchPrompt } = await import('./ai/chat_generator.js');
  const p = buildBatchPrompt({ count: 4, stream: { title: 'cozy games', streamer: 'Nori', viewers: 50, phase: 'warmup', pressure: 0.2 } });
  const msgs = [{ role: 'system', content: p.system }, { role: 'user', content: p.user }];
  step('prompt chars ' + (p.system+p.user).length);
  const rt = await createRuntime(MODEL_CATALOG.find(m => m.id === MODEL), {});
  const lt = performance.now();
  await rt.load(() => {});
  step('loaded in ' + ((performance.now()-lt)/1000).toFixed(1) + 's');
  const res = { model: MODEL };
  const t1 = performance.now();
  const pre = await rt.chat(msgs, { maxTokens: 2, jsonSchema: BATCH_SCHEMA });
  res.prefill = { seconds: (performance.now() - t1) / 1000, usage: pre.usage, sample: pre.text.slice(0, 80) };
  step('prefill ' + JSON.stringify(res.prefill));
  const t2 = performance.now();
  const dec = await rt.chat(msgs, { maxTokens: 100, jsonSchema: BATCH_SCHEMA });
  res.decode_schema = { seconds: (performance.now() - t2) / 1000, usage: dec.usage };
  step('decode+schema ' + JSON.stringify(res.decode_schema));
  const t3 = performance.now();
  const nogram = await rt.chat(msgs, { maxTokens: 100, json: false });
  res.decode_plain = { seconds: (performance.now() - t3) / 1000, usage: nogram.usage };
  step('decode no-schema ' + JSON.stringify(res.decode_plain));
  await rt.unload();
  step('unloaded');
  const lt2 = performance.now();
  const rt2 = await createRuntime(MODEL_CATALOG.find(m => m.id === MODEL), {});
  await rt2.load(() => {});
  res.reloadSeconds = (performance.now() - lt2) / 1000;
  step('reloaded in ' + res.reloadSeconds.toFixed(1) + 's');
  const t4 = performance.now();
  const again = await rt2.chat(msgs, { maxTokens: 40, jsonSchema: BATCH_SCHEMA });
  res.afterReload = { seconds: (performance.now() - t4)/1000, usage: again.usage };
  step('after reload ' + JSON.stringify(res.afterReload));
  await rt2.unload();
  return res;
}, MODEL);
console.log(JSON.stringify(out, null, 1));
await ctx.close();
